"""Generate firmware room constants from the authoritative laptop configuration."""
import argparse
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from indoor_ble.config import load_config


def generate(config):
    lines=["#pragma once","// Generated by tools/configure_firmware.py; edit the source JSON.",
           f"constexpr uint16_t RECEIVER_PORT={config['network']['udp_port']};",
           f"constexpr uint16_t CONFIGURED_TAG_ID={config['tag_id']};",
           "struct AnchorPlacement { const char *id; uint16_t wireId; float x,y; };",
           "constexpr AnchorPlacement ANCHOR_PLACEMENTS[] = {"]
    for name in ("A","B","C"):
        a=config["anchors"][name]
        lines.append(f'  {{"{name}",{a["wire_id"]},{float(a["x"])}f,{float(a["y"])}f}},')
    lines.append("};\n")
    return "\n".join(lines)


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--config",default=str(ROOT/"config/room.json"))
    args=p.parse_args(); cfg=load_config(args.config)
    target=ROOT/"firmware/libraries/IndoorBLE/src/RoomConfig.h"
    target.write_text(generate(cfg),encoding="utf-8")
    for sketch in ("tag_minimal","tag_channels"):
        path=ROOT/f"firmware/{sketch}/TagConfig.h"
        text=path.read_text(encoding="utf-8")
        import re
        path.write_text(re.sub(r"TAG_ID = \d+;",f"TAG_ID = {cfg['tag_id']};",text),encoding="utf-8")
    print(f"Updated {target} and tag IDs. Recompile/reflash anchors after coordinate changes.")
